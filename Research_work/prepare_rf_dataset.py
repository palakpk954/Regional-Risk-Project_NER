"""
Random Forest Dataset Preparation Pipeline for Landslide Susceptibility

This script expects the following files to be present in the directory:
- GLC_Meghalaya_clean.csv (Generated by the cleaning pipeline)
- dem.tif (A Digital Elevation Model, e.g., SRTM 30m)
- lulc.tif (Land Use / Land Cover raster)
- (Optional) ndvi.tif (Vegetation index)

Outputs:
- random_forest_dataset.csv (Ready for ML training)
"""

import os
import sys
import numpy as np
import pandas as pd
import geopandas as gpd
from shapely.geometry import Point
try:
    import rasterio
    import xarray as xr
    from xrspatial import slope, aspect, curvature
except ImportError:
    print("Please install required libraries: pip install rasterio xarray xarray-spatial geopandas")
    sys.exit(1)

# ---------------------------------------------------------
# 1. Configuration and Checks
# ---------------------------------------------------------
DIR = r"c:\Users\HP\Desktop\Research wokr"

EVENTS_CSV = os.path.join(DIR, "GLC_Meghalaya_clean.csv")
DEM_PATH = os.path.join(DIR, "dem.tif")
LULC_PATH = os.path.join(DIR, "lulc.tif")
OUT_CSV = os.path.join(DIR, "landslide_research_outputs", "random_forest_dataset.csv")

missing = []
for p in [EVENTS_CSV, DEM_PATH]:
    if not os.path.exists(p): missing.append(p)

if missing:
    print("MISSING FILES:", missing)
    print("Please download your DEM (dem.tif) and place it in the project folder before running this script.")
    print("You can get SRTM 30m DEM from USGS EarthExplorer (earthexplorer.usgs.gov).")
    sys.exit(1)

print("All required base files found. Starting spatial extraction...")

# ---------------------------------------------------------
# 2. Load Landslide Events
# ---------------------------------------------------------
events = pd.read_csv(EVENTS_CSV)
# Filter for only confident locations (e.g. within 5km accuracy)
events = events[events['location_uncertainty_km'] <= 5.0].copy()

# Create GeoDataFrame for the positive points
pos_pts = gpd.GeoDataFrame(
    events, 
    geometry=gpd.points_from_xy(events.longitude, events.latitude),
    crs="EPSG:4326"
)
pos_pts['landslide'] = 1

# ---------------------------------------------------------
# 3. Generate Background (Non-Landslide) Samples
# ---------------------------------------------------------
# To train a Random Forest, we need negative samples. We will generate random 
# points within the bounding box of Meghalaya, ensuring they are at least 1km 
# away from any known landslide event to reduce false-negative leakage.

print(f"Generating background samples against {len(pos_pts)} landslide points...")
minx, miny, maxx, maxy = pos_pts.total_bounds
# Expand bounding box slightly for Meghalaya region
minx, maxx = minx - 0.5, maxx + 0.5
miny, maxy = miny - 0.2, maxy + 0.2

np.random.seed(42)
num_negatives = len(pos_pts) * 5  # 5:1 ratio of negatives to positives
neg_points = []
while len(neg_points) < num_negatives:
    rand_lon = np.random.uniform(minx, maxx)
    rand_lat = np.random.uniform(miny, maxy)
    p = Point(rand_lon, rand_lat)
    
    # Simple buffer check to avoid placing negatives directly on top of known landslides
    # (In a strict pipeline, you would reproject to a metric CRS for exact distance)
    if not any(p.distance(geom) < 0.01 for geom in pos_pts.geometry): # ~1km buffer
        neg_points.append(p)

neg_df = gpd.GeoDataFrame(geometry=neg_points, crs="EPSG:4326")
neg_df['landslide'] = 0
neg_df['event_id'] = [f"NEG_{i}" for i in range(len(neg_points))]

# Combine datasets
all_pts = pd.concat([pos_pts[['event_id', 'geometry', 'landslide']], neg_df], ignore_index=True)

# ---------------------------------------------------------
# 4. Extract Topographic Features from DEM
# ---------------------------------------------------------
print("Extracting Elevation, Slope, and Aspect from DEM...")
# We use rasterio to sample values at the coordinate points

def sample_raster(raster_path, points, col_name):
    if not os.path.exists(raster_path):
        print(f"Warning: {raster_path} not found. Skipping {col_name} extraction.")
        points[col_name] = np.nan
        return points
        
    with rasterio.open(raster_path) as src:
        # Reproject points if CRS doesn't match
        if points.crs != src.crs:
            points = points.to_crs(src.crs)
            
        coords = [(x,y) for x,y in zip(points.geometry.x, points.geometry.y)]
        values = [val[0] for val in src.sample(coords)]
        points[col_name] = values
    return points

# Sample Elevation directly
all_pts = sample_raster(DEM_PATH, all_pts, "elevation")

# To get slope/aspect, we open the DEM with xarray and compute them, then save temporarily
# Note: For exact metric slopes, DEM should ideally be projected in UTM, but we will assume it's suitable.
try:
    with rasterio.open(DEM_PATH) as src:
        dem_data = src.read(1)
        # Handle nodata
        if src.nodata is not None:
            dem_data = np.where(dem_data == src.nodata, np.nan, dem_data)
            
        # We need an xarray DataArray for xrspatial
        da = xr.DataArray(dem_data)
        
        # Calculate slope and aspect
        slope_da = slope(da)
        aspect_da = aspect(da)
        
        # Save temporary rasters
        meta = src.meta.copy()
        meta.update(dtype=rasterio.float32)
        
        with rasterio.open('tmp_slope.tif', 'w', **meta) as dst:
            dst.write(slope_da.values.astype(rasterio.float32), 1)
        with rasterio.open('tmp_aspect.tif', 'w', **meta) as dst:
            dst.write(aspect_da.values.astype(rasterio.float32), 1)
            
    # Sample the temporary rasters
    all_pts = sample_raster('tmp_slope.tif', all_pts, "slope")
    all_pts = sample_raster('tmp_aspect.tif', all_pts, "aspect")
    
    # Cleanup
    os.remove('tmp_slope.tif')
    os.remove('tmp_aspect.tif')
except Exception as e:
    print(f"Could not calculate Slope/Aspect. Ensure xarray-spatial is installed. Error: {e}")
    all_pts['slope'] = np.nan
    all_pts['aspect'] = np.nan

# ---------------------------------------------------------
# 5. Extract Land Cover (LULC)
# ---------------------------------------------------------
print("Extracting Land Use / Land Cover...")
all_pts = sample_raster(LULC_PATH, all_pts, "lulc_class")

# ---------------------------------------------------------
# 6. Save Final Dataset
# ---------------------------------------------------------
# Clean up missing values (points that fell outside the DEM/LULC raster boundaries)
final_df = pd.DataFrame(all_pts.drop(columns=['geometry']))
final_df = final_df.dropna(subset=['elevation'])

os.makedirs(os.path.join(DIR, "landslide_research_outputs"), exist_ok=True)
final_df.to_csv(OUT_CSV, index=False)

print(f"\nSUCCESS! Random Forest dataset saved to: {OUT_CSV}")
print(f"Total rows: {len(final_df)} ({final_df['landslide'].sum()} positive events, {len(final_df)-final_df['landslide'].sum()} background samples)")
print("\nYou are now ready to train your Random Forest model!")
